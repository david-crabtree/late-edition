// Generate THIRD_PARTY_NOTICES.md from the production dependency tree.
//
// Everything shipped inside the app that somebody else wrote, with its licence and, where
// the licence asks for it, the licence text itself. Apache 2.0 section 4(d) and the BSD and
// MIT families all require the notice to travel with the binary, so this file is bundled
// into the app's resources and the About screen opens it offline.
//
//   node scripts/third-party-notices.mjs          write the file
//   node scripts/third-party-notices.mjs --check  fail if it is out of date
//
// It exits non-zero when a dependency carries a licence that cannot be redistributed in a
// closed or source-available build — the GPL family — or none that can be read at all.
// Finding that at release time is the expensive version of finding it here.

import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'THIRD_PARTY_NOTICES.md');

/** Licences that must not appear in a bundled dependency. Copyleft reaches the whole build. */
const FORBIDDEN = /\b(GPL-[23]|AGPL|LGPL|SSPL|CC-BY-NC|CC-BY-SA|BUSL)/i;

/** The file a package keeps its licence text in, under any of the usual spellings. */
function licenceText(dir) {
  let names;
  try {
    names = readdirSync(dir);
  } catch {
    return '';
  }
  const file = names.find((n) => /^(LICEN[CS]E|COPYING)(\.(md|txt))?$/i.test(n));
  if (!file) return '';
  try {
    return readFileSync(join(dir, file), 'utf8').trim();
  } catch {
    return '';
  }
}

/**
 * Everything that ships, read from the lockfile.
 *
 * `npm ls` would answer the same question, but it is a subprocess — and on Windows npm is
 * a .cmd shim that recent Node refuses to spawn without a shell, while passing arguments
 * through a shell concatenates rather than escapes them. The lockfile is already in the
 * repo, already exact, and reads the same on every machine and in CI.
 */
function productionTree() {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
  const out = [];
  for (const [path, meta] of Object.entries(lock.packages ?? {})) {
    if (!path || meta.dev) continue; // the root entry, and anything dev-only
    out.push({
      name: path.replace(/^(.*\/)?node_modules\//, ''),
      version: meta.version,
      path: join(root, path),
      declared: typeof meta.license === 'string' ? meta.license : '',
    });
  }
  return out.sort((a, b) => a.name.localeCompare(b.name));
}

const pkgs = productionTree();
const problems = [];
const sections = [];

for (const p of pkgs) {
  const dir = p.path ?? join(root, 'node_modules', p.name);
  let meta = {};
  try {
    meta = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  } catch {
    /* read what we can; the check below catches a package we could not read at all */
  }
  const licence =
    p.declared ||
    (typeof meta.license === 'string'
      ? meta.license
      : (meta.license?.type ?? (Array.isArray(meta.licenses) ? meta.licenses[0]?.type : ''))) ||
    '';

  if (!licence) problems.push(`${p.name}@${p.version}: no licence declared`);
  else if (FORBIDDEN.test(licence)) problems.push(`${p.name}@${p.version}: ${licence}`);

  const text = licenceText(dir);
  sections.push(
    [
      `### ${p.name} ${p.version}`,
      '',
      `**Licence:** ${licence || 'UNKNOWN'}${meta.homepage ? ` · ${meta.homepage}` : ''}`,
      ...(text ? ['', '```', text, '```'] : ['', '_No licence file ships with this package._']),
      '',
    ].join('\n'),
  );
}

const body = `# Third party notices

Late Edition bundles the packages below. Each is the property of its own authors and is
used under its own licence, reproduced here where the package ships the text.

Generated by \`scripts/third-party-notices.mjs\` from the production dependency tree.
Regenerate it on every release: a notice file that is out of date is worse than none,
because it makes a claim about what is in the build that is no longer true.

${pkgs.length} packages.

---

${sections.join('\n')}`;

if (problems.length) {
  console.error('FAIL  dependencies that cannot ship in this build:\n');
  for (const p of problems) console.error(`      ${p}`);
  console.error('\n      Replace them, or the licence of the whole build is in question.');
  process.exit(1);
}

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== body) {
    console.error('FAIL  THIRD_PARTY_NOTICES.md is out of date. Run:');
    console.error('      node scripts/third-party-notices.mjs');
    process.exit(1);
  }
  console.log(`OK    third party notices current · ${pkgs.length} packages`);
} else {
  writeFileSync(OUT, body, 'utf8');
  console.log(`OK    third party notices written · ${pkgs.length} packages`);
}
